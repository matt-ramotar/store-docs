import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
const label = process.argv[2];
if (!/^[a-z0-9-]+$/.test(label ?? "")) throw new Error("A named manifest is required");
const paths = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], {encoding:"utf8"}).split("\0").filter(Boolean).filter(p => !p.startsWith("evidence/design-revision/") && !p.endsWith(".tsbuildinfo"));
const files = [...new Set(paths)].sort().map(path => ({path, sha256:createHash("sha256").update(readFileSync(path)).digest("hex")}));
const manifest = {capturedAt:new Date().toISOString(), head:execFileSync("git", ["rev-parse", "HEAD"], {encoding:"utf8"}).trim(), productDigest:createHash("sha256").update(JSON.stringify(files)).digest("hex"), files};
writeFileSync(`evidence/design-revision/${label}-manifest.json`, JSON.stringify(manifest, null, 2)+"\n");
console.log(JSON.stringify({label,productDigest:manifest.productDigest,files:files.length}));
